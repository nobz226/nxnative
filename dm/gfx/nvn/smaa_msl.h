// SMAA 1x shaders (Metal), compiled at run time by smaa_apply in nvn_mtl.m. Ported from SMAA.hlsl (Jorge Jimenez et al., MIT, dm/third_party/smaa/LICENSE.txt):
// luma edge detection, orthogonal pattern search with the area and search lookup tables, neighborhood blending; no diagonal or corner detection (the "medium" preset)
#pragma once
static const char *smaa_msl =
    "#include <metal_stdlib>\n"
    "using namespace metal;\n"
    "// SMAA 1x (Jimenez et al., MIT; ported from SMAA.hlsl: luma edges, orthogonal search, no diagonal or corner detection, the \"medium\" preset)\n"
    "struct V { float4 p [[position]]; float2 uv; };\n"
    "vertex V vs(uint id [[vertex_id]]) { float2 uv = float2((id << 1) & 2, id & 2); V o; o.p = float4(uv * float2(2, -2) + float2(-1, 1), 0, 1); o.uv = uv; return o; }\n"
    "struct P { float4 rt; uint srgb; };   // rt = (1/w, 1/h, w, h); srgb: the color texture decodes sRGB (edges are found on gamma values)\n"
    "constant float TH = 0.1, LCA = 2.0, STEPS = 8.0;\n"
    "static float luma(float3 c, uint srgb) { float l = dot(c, float3(0.2126, 0.7152, 0.0722)); return srgb ? pow(max(l, 0.0), 1.0 / 2.2) : l; }\n"
    "fragment float2 fs_edges(V in [[stage_in]], texture2d<float> c [[texture(0)]], sampler ls [[sampler(0)]], constant P &p [[buffer(0)]]) {\n"
    "    float2 uv = in.uv; float4 rt = p.rt;\n"
    "    float4 o0 = uv.xyxy + rt.xyxy * float4(-1, 0, 0, -1), o1 = uv.xyxy + rt.xyxy * float4(1, 0, 0, 1), o2 = uv.xyxy + rt.xyxy * float4(-2, 0, 0, -2);\n"
    "    float L = luma(c.sample(ls, uv).rgb, p.srgb), Ll = luma(c.sample(ls, o0.xy).rgb, p.srgb), Lt = luma(c.sample(ls, o0.zw).rgb, p.srgb);\n"
    "    float4 delta; delta.xy = abs(L - float2(Ll, Lt));\n"
    "    float2 edges = step(TH, delta.xy);\n"
    "    if (edges.x + edges.y == 0.0) discard_fragment();\n"
    "    float Lr = luma(c.sample(ls, o1.xy).rgb, p.srgb), Lb = luma(c.sample(ls, o1.zw).rgb, p.srgb);\n"
    "    delta.zw = abs(L - float2(Lr, Lb));\n"
    "    float2 md = max(delta.xy, delta.zw);\n"
    "    float Lll = luma(c.sample(ls, o2.xy).rgb, p.srgb), Ltt = luma(c.sample(ls, o2.zw).rgb, p.srgb);\n"
    "    delta.zw = abs(float2(Ll, Lt) - float2(Lll, Ltt));\n"
    "    md = max(md.xy, delta.zw);\n"
    "    float fd = max(md.x, md.y);\n"
    "    edges *= step(fd, LCA * delta.xy);\n"
    "    return edges;\n"
    "}\n"
    "static float searchlen(texture2d<float> st, sampler ps, float2 e, float off) {\n"
    "    float2 scale = float2(66.0, 33.0) * float2(0.5, -1.0), bias = float2(66.0, 33.0) * float2(off, 1.0);\n"
    "    scale += float2(-1.0, 1.0); bias += float2(0.5, -0.5);\n"
    "    scale /= float2(64.0, 16.0); bias /= float2(64.0, 16.0);\n"
    "    return st.sample(ps, fma(scale, e, bias), level(0)).r;\n"
    "}\n"
    "static float sxl(texture2d<float> et, texture2d<float> st, sampler ls, sampler ps, float2 uv, float end, float4 rt) {\n"
    "    float2 e = float2(0.0, 1.0);\n"
    "    while (uv.x > end && e.g > 0.8281 && e.r == 0.0) { e = et.sample(ls, uv, level(0)).rg; uv = fma(-float2(2.0, 0.0), rt.xy, uv); }\n"
    "    float off = fma(-(255.0 / 127.0), searchlen(st, ps, e, 0.0), 3.25);\n"
    "    return fma(rt.x, off, uv.x);\n"
    "}\n"
    "static float sxr(texture2d<float> et, texture2d<float> st, sampler ls, sampler ps, float2 uv, float end, float4 rt) {\n"
    "    float2 e = float2(0.0, 1.0);\n"
    "    while (uv.x < end && e.g > 0.8281 && e.r == 0.0) { e = et.sample(ls, uv, level(0)).rg; uv = fma(float2(2.0, 0.0), rt.xy, uv); }\n"
    "    float off = fma(-(255.0 / 127.0), searchlen(st, ps, e, 0.5), 3.25);\n"
    "    return fma(-rt.x, off, uv.x);\n"
    "}\n"
    "static float syu(texture2d<float> et, texture2d<float> st, sampler ls, sampler ps, float2 uv, float end, float4 rt) {\n"
    "    float2 e = float2(1.0, 0.0);\n"
    "    while (uv.y > end && e.r > 0.8281 && e.g == 0.0) { e = et.sample(ls, uv, level(0)).rg; uv = fma(-float2(0.0, 2.0), rt.xy, uv); }\n"
    "    float off = fma(-(255.0 / 127.0), searchlen(st, ps, e.gr, 0.0), 3.25);\n"
    "    return fma(rt.y, off, uv.y);\n"
    "}\n"
    "static float syd(texture2d<float> et, texture2d<float> st, sampler ls, sampler ps, float2 uv, float end, float4 rt) {\n"
    "    float2 e = float2(1.0, 0.0);\n"
    "    while (uv.y < end && e.r > 0.8281 && e.g == 0.0) { e = et.sample(ls, uv, level(0)).rg; uv = fma(float2(0.0, 2.0), rt.xy, uv); }\n"
    "    float off = fma(-(255.0 / 127.0), searchlen(st, ps, e.gr, 0.5), 3.25);\n"
    "    return fma(-rt.y, off, uv.y);\n"
    "}\n"
    "static float2 area(texture2d<float> at, sampler ls, float2 dist, float e1, float e2) {\n"
    "    float2 t = fma(float2(16.0, 16.0), round(4.0 * float2(e1, e2)), dist);\n"
    "    t = fma(float2(1.0 / 160.0, 1.0 / 560.0), t, 0.5 * float2(1.0 / 160.0, 1.0 / 560.0));\n"
    "    return at.sample(ls, t, level(0)).rg;\n"
    "}\n"
    "fragment float4 fs_weights(V in [[stage_in]], texture2d<float> et [[texture(0)]], texture2d<float> at [[texture(1)]], texture2d<float> st [[texture(2)]],\n"
    "                           sampler ls [[sampler(0)]], sampler ps [[sampler(1)]], constant P &p [[buffer(0)]]) {\n"
    "    float2 uv = in.uv; float4 rt = p.rt; float2 pix = uv * rt.zw;\n"
    "    float4 o0 = uv.xyxy + rt.xyxy * float4(-0.25, -0.125, 1.25, -0.125), o1 = uv.xyxy + rt.xyxy * float4(-0.125, -0.25, -0.125, 1.25);\n"
    "    float4 o2 = float4(o0.xz, o1.yw) + float4(-2.0, 2.0, -2.0, 2.0) * rt.xxyy * STEPS;\n"
    "    float4 w = 0.0;\n"
    "    float2 e = et.sample(ls, uv).rg;\n"
    "    if (e.g > 0.0) {   // an edge at the north\n"
    "        float3 co; co.x = sxl(et, st, ls, ps, o0.xy, o2.x, rt); co.y = o1.y;\n"
    "        float2 d; d.x = co.x;\n"
    "        float e1 = et.sample(ls, co.xy, level(0)).r;\n"
    "        co.z = sxr(et, st, ls, ps, o0.zw, o2.y, rt); d.y = co.z;\n"
    "        d = abs(round(fma(rt.zz, d, -pix.xx)));\n"
    "        float e2 = et.sample(ls, co.zy, level(0), int2(1, 0)).r;\n"
    "        w.rg = area(at, ls, sqrt(d), e1, e2);\n"
    "    }\n"
    "    if (e.r > 0.0) {   // an edge at the west\n"
    "        float3 co; co.y = syu(et, st, ls, ps, o1.xy, o2.z, rt); co.x = o0.x;\n"
    "        float2 d; d.x = co.y;\n"
    "        float e1 = et.sample(ls, co.xy, level(0)).g;\n"
    "        co.z = syd(et, st, ls, ps, o1.zw, o2.w, rt); d.y = co.z;\n"
    "        d = abs(round(fma(rt.ww, d, -pix.yy)));\n"
    "        float e2 = et.sample(ls, co.xz, level(0), int2(0, 1)).g;\n"
    "        w.ba = area(at, ls, sqrt(d), e1, e2);\n"
    "    }\n"
    "    return w;\n"
    "}\n"
    "fragment float4 fs_blend(V in [[stage_in]], texture2d<float> c [[texture(0)]], texture2d<float> bt [[texture(1)]], sampler ls [[sampler(0)]], constant P &p [[buffer(0)]]) {\n"
    "    float2 uv = in.uv; float4 rt = p.rt; float4 off = uv.xyxy + rt.xyxy * float4(1, 0, 0, 1);\n"
    "    float4 a; a.x = bt.sample(ls, off.xy).a; a.y = bt.sample(ls, off.zw).g; a.wz = bt.sample(ls, uv).xz;\n"
    "    float4 m = c.sample(ls, uv);\n"
    "    if (dot(a, float4(1.0)) < 1e-5) return m;\n"
    "    bool h = max(a.x, a.z) > max(a.y, a.w);\n"
    "    float4 bo = h ? float4(a.x, 0.0, a.z, 0.0) : float4(0.0, a.y, 0.0, a.w);\n"
    "    float2 bw = h ? a.xz : a.yw;\n"
    "    bw /= dot(bw, float2(1.0));\n"
    "    float4 bc = fma(bo, float4(rt.xy, -rt.xy), uv.xyxy);\n"
    "    float4 r = bw.x * c.sample(ls, bc.xy, level(0)) + bw.y * c.sample(ls, bc.zw, level(0));\n"
    "    return float4(r.rgb, m.a);\n"
    "}\n";
